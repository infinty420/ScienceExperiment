/**
 * 纯 TS SHA-256（不依赖 WebCrypto / crypto.subtle）
 * 目的：鸿蒙 WebView 在 resource:// opaque origin 下不保证 crypto.subtle 可用，
 * 实验快照仍需稳定哈希做完整性校验与去重。
 */
